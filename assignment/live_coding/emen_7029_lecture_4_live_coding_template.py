def create_dataset(n: int, seed: jax.random.PRNGKey) -> Tuple[jax.Array, jax.Array]:
  # First, let us create the X

  # First, let us sample R
  # To keep things simple, let's make R in [0, 1]
  # QUESTION: What is the shape of r?
  r = jax.random.uniform(seed, (n,))

  # Make a new random seed
  seed = jax.random.PRNGKey(1)
  # Next, sample phi
  # QUESTION: What is the range of phi?
  phi = jax.random.uniform(seed, (n,)) * 2 * jnp.pi

  # QUESTION: What does stack do?
  X = jnp.stack([r, phi], axis=1)

  # Now, let us create the Y (outputs)
  Y = jnp.stack([r * jnp.cos(phi), r * jnp.sin(phi)], axis=1)

  return X, Y

# Need some randomness to generate a dataset
