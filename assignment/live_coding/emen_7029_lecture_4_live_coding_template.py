import torch
import numpy as np

# Create dataset and parameters
seed = jax.random.PRNGKey(0)
n = 1000 # number of datapoints
X, Y = create_dataset(n, seed)
X = torch.from_numpy(np.array(X))
Y = torch.from_numpy(np.array(Y))

# Next, we must create our neural network parameters
def make_parameters(input_size, output_size) -> Tuple[torch.Tensor, torch.Tensor]:
  # Torch autograd works differently from jax
  #
  # We must explicitly tell pytorch which terms are parameters, we do this
  # by creating a nn.Parameter(my_torch_array)
  b = torch.randn(size=(output_size,))
  W = torch.randn(size=(input_size, output_size)) / (input_size ** 0.5)

  return (
    torch.nn.Parameter(b), # Bias b
    torch.nn.Parameter(W) # Weight W
  )

b_1, W_1 = make_parameters(d_x, d_h)
b_2, W_2 = make_parameters(d_h, d_y)

thetas = [
    [b_1, W_1],
    [b_2, W_2]
]

# Construct MLP

# QUESTION What is the type signature of theta?
def linear_layer(x: torch.Tensor, theta: Tuple[torch.Tensor, torch.Tensor]) -> torch.Tensor:
  b, W = theta
  return b + W.T @ x


# QUESTION What is the type signature of thetas?
def mlp(x, thetas):
  theta_1, theta_2 = thetas
  z_1 = linear_layer(x, theta_1)
  z_1 = torch.sigmoid(z_1)
  z_2 = linear_layer(z_1, theta_2)
  # QUESTION: Do we want activation after z_2?
  return z_2

# Test our MLP
x = X[0]
y_prediction = mlp(x, thetas)
print(y_prediction)
# MLP: R^(d_x) x Theta |-> R^(d_y)
# Parallel MLP: R^(n, d_x) x Theta |-> R^(n, d_y)
torch.vmap(mlp)
# f: R^(n, d_x) x Theta^(n) |-> R^(n, d_y)
# f: R^(n, d_x) x Theta |-> R^(n, d_y)
parallel_mlp = torch.vmap(mlp, in_dims=(0, None))

Y_prediction = parallel_mlp(X, thetas)
print(Y_prediction.shape)

# Now create our loss function
def L(x: jax.Array, y: jax.Array, thetas: Tuple[Tuple[jax.Array, jax.Array], Tuple[jax.Array, jax.Array]]) -> jax.Array:
  # QUESTION: What are shapes?
  # QUESTION: What is the equation?

  # We have many datapoints
  # We want to compute all the y predictions at the same time
  # So use the parallel mlp
  y_prediction = parallel_mlp(x, thetas)
  return torch.sum((y - y_prediction) ** 2)

# Now time for gradients
# QUESTION: What function do we take the gradient of?


# Since torch does not have grad, we must explicitly create an optimizer
# And tell the optimizer which terms to optimize
# It can only take a list of tensors,
# So we use this * notation to unpack the 2d list into a single list
# 1. Create parameters torch.nn.Parameter([W])
# 2. Give the optimizer a list of these parameters
parameter_list = thetas[0] + thetas[1] # This will create a new list [theta_00, theta_01] + [theta_10, theta_11] = [theta_00, theta_01, theta_10, theta_11]
optimizer = torch.optim.SGD(parameter_list, lr=0.00005) # lr == learning rate == alpha

# Torch does not have jax.grad unfortunately.
# Instead, torch records/stores every intermediate operations
# For example, z = x + y, torch will store x, y, z until backward is called
# so instead:

# 1. Run the loss function on the dataset
# 2. Call loss.backward() on the loss to compute gradients
# 3. Call optimizer.step() to update parameters using the computed gradient
# 4. Call loss.zero_grad() to delete the gradient after we are done with it
loss = L(X, Y, thetas)

# Now, each of the stored terms will receive a .grad attribute
# For example, with z = x + y
# z.grad, y.grad, x.grad will be populated
loss.backward()

# Next, we can update each parameter using step
# This does z = z - alpha * z.grad
optimizer.step()

# Finally, we must set each z.grad = 0
# Otherwise the gradients from each iteration will sum together
optimizer.zero_grad()

# Implement torch loop


num_iterations = 100_000

for iteration in range(num_iterations):
  loss = L(X, Y, thetas)
  if iteration % 1_000 == 0:
    # JIT makes things much faster
    print(loss)
  # 1. Compute gradient
  loss.backward()
  # Let us print the loss to see if it decreases
  # 2. Change theta slightly
  optimizer.step()
  optimizer.zero_grad()

