# Create a multilayer perceptron (MLP)
# First, let us create some parameters
# Then, we will define the layer
# QUESTION: What are the two parts in a neural network layer?

def make_parameters(input_size, output_size, key) -> Tuple[jax.Array, jax.Array]:
  W_seed, b_seed = jax.random.split(key)
  return (
    jax.random.normal(b_seed, shape=(output_size,)), # Bias b
    jax.random.normal(W_seed, shape=(input_size, output_size)) / jnp.sqrt(input_size) # Weight W
  )

seed = jax.random.PRNGKey(1)
b_1, W_1 = make_parameters(d_x, d_h, seed)

