# Our MLP is only designed to take a single input
# We will use vmap a very powerful function to make our MLP
# work over the entire dataset
# vmap takes a function and returns a new function that works over an array of inputs

# f: R^(d_x), thetas |-> R^(d_y)
# If we vmap(f), we have
# vmap(f): R^(n * d_x), thetas^(n) |-> R^(n * d_y)

# But actually, we do not want to map theta^(n)
# We want to parallelize the inputs X and outputs Y only!
# vmap(f): R^(n * d_x), thetas |-> R^(n * d_y)
# And so, we pass the in_axes argument
# It says: for the zeroth argument, parallelize on the zero axis
# For the first argument, None means do not parallelize!
parallel_mlp = jax.vmap(mlp, in_axes=(0, None))

